// Writes the licence of every package in the bundle next to it, which MIT and BSD ask for.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ALLOWED = new Set(['MIT', 'BSD-3-Clause']);
const LICENSE_FILE = /^licen[cs]e(\.(md|txt))?$/i;
const PACKAGE_DIR = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//;

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const output = path.join(root, '..', 'note-editor.licenses.txt');
const { inputs } = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/.bundle-meta.json'), 'utf8'));

const packageDirs = new Set(Object.keys(inputs).map((file) => PACKAGE_DIR.exec(file)?.[1]).filter(Boolean));

// Packages grouped by licence text, because most of them repeat the same one.
const byText = new Map();
for (const dir of packageDirs) {
    const absolute = path.join(root, dir);
    const { name, version, license } = JSON.parse(fs.readFileSync(path.join(absolute, 'package.json'), 'utf8'));
    const file = fs.readdirSync(absolute).find((entry) => LICENSE_FILE.test(entry));
    if (!ALLOWED.has(license)) throw new Error(`${name}: licence "${license}" needs a review`);
    if (!file) throw new Error(`${name}: no licence file`);
    const text = fs.readFileSync(path.join(absolute, file), 'utf8').trim();
    if (!byText.has(text)) byText.set(text, []);
    byText.get(text).push(`${name} ${version} (${license})`);
}

const groups = [...byText].map(([text, packages]) => ({ text, packages: packages.sort() }))
    .sort((a, b) => a.packages[0].localeCompare(b.packages[0]));
const sections = groups.map(({ text, packages }) => `${packages.join('\n')}\n\n${text}`);
const header = 'Third-party licences for note-editor.bundle.js. Generated by npm run build in frontend/editor-src.';
fs.writeFileSync(output, `${[header, ...sections].join(`\n\n${'-'.repeat(72)}\n\n`)}\n`);
console.log(`Licences of ${packageDirs.size} packages written to ${path.basename(output)}`);
